-- Migración oficial de Pedido para PoliRestaurante.
-- Crea la tabla y sus relaciones sin eliminar ni actualizar registros existentes.

BEGIN;

DO $$
BEGIN
    CREATE TYPE tipo_pedido AS ENUM ('SALON', 'PARA_LLEVAR', 'DOMICILIO');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
    CREATE TYPE estado_pedido AS ENUM (
        'PENDIENTE',
        'EN_PREPARACION',
        'LISTO',
        'ENTREGADO',
        'CANCELADO'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS pedido (
    id_pedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mesa integer,
    id_mesero integer,
    id_cliente integer,
    tipo tipo_pedido NOT NULL,
    estado estado_pedido NOT NULL DEFAULT 'PENDIENTE',
    valor_total numeric(12, 2) NOT NULL DEFAULT 0,
    observaciones varchar(500),
    fecha_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_ultima_actualizacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pedido_valor_total_no_negativo CHECK (valor_total >= 0),
    CONSTRAINT fk_pedido_mesa
        FOREIGN KEY (id_mesa) REFERENCES mesa (id_mesa) ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_mesero
        FOREIGN KEY (id_mesero) REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (id_cliente) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_pedido_id_mesa ON pedido (id_mesa);
CREATE INDEX IF NOT EXISTS ix_pedido_id_mesero ON pedido (id_mesero);
CREATE INDEX IF NOT EXISTS ix_pedido_id_cliente ON pedido (id_cliente);
CREATE INDEX IF NOT EXISTS ix_pedido_estado ON pedido (estado);

CREATE OR REPLACE FUNCTION actualizar_fecha_pedido()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_ultima_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_pedido_fecha_actualizacion'
          AND tgrelid = 'pedido'::regclass
    ) THEN
        CREATE TRIGGER trg_pedido_fecha_actualizacion
        BEFORE UPDATE ON pedido
        FOR EACH ROW
        EXECUTE FUNCTION actualizar_fecha_pedido();
    END IF;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_pago_id_pedido'
          AND conrelid = 'pago'::regclass
    ) THEN
        ALTER TABLE pago
            ADD CONSTRAINT uq_pago_id_pedido UNIQUE (id_pedido);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_pago_pedido'
          AND conrelid = 'pago'::regclass
    ) THEN
        ALTER TABLE pago
            ADD CONSTRAINT fk_pago_pedido
            FOREIGN KEY (id_pedido)
            REFERENCES pedido (id_pedido)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_entrega_id_pedido'
          AND conrelid = 'entrega'::regclass
    ) THEN
        ALTER TABLE entrega
            ADD CONSTRAINT uq_entrega_id_pedido UNIQUE (id_pedido);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_entrega_pedido'
          AND conrelid = 'entrega'::regclass
    ) THEN
        ALTER TABLE entrega
            ADD CONSTRAINT fk_entrega_pedido
            FOREIGN KEY (id_pedido)
            REFERENCES pedido (id_pedido)
            ON DELETE RESTRICT;
    END IF;
END
$$;

COMMIT;
