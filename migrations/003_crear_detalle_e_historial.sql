-- Completa el modelo relacional oficial con detalle_pedido e historial_estado.
-- Es idempotente y no elimina ni modifica registros existentes.

BEGIN;

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido integer NOT NULL,
    id_producto integer NOT NULL,
    cantidad integer NOT NULL,
    precio_unitario numeric(12, 2) NOT NULL,
    comentarios varchar(500),
    CONSTRAINT fk_detalle_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto
        FOREIGN KEY (id_producto) REFERENCES producto (id_producto) ON DELETE RESTRICT,
    CONSTRAINT ck_detalle_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio_no_negativo CHECK (precio_unitario >= 0),
    CONSTRAINT uq_detalle_pedido_producto UNIQUE (id_pedido, id_producto)
);

CREATE INDEX IF NOT EXISTS ix_detalle_pedido_id_pedido
    ON detalle_pedido (id_pedido);
CREATE INDEX IF NOT EXISTS ix_detalle_pedido_id_producto
    ON detalle_pedido (id_producto);

CREATE TABLE IF NOT EXISTS historial_estado (
    id_historial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido integer NOT NULL,
    id_usuario_cambio integer,
    estado estado_pedido NOT NULL,
    fecha timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion varchar(500),
    CONSTRAINT fk_historial_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_historial_usuario
        FOREIGN KEY (id_usuario_cambio)
        REFERENCES usuario (id_usuario)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_historial_estado_id_pedido
    ON historial_estado (id_pedido);
CREATE INDEX IF NOT EXISTS ix_historial_estado_id_usuario_cambio
    ON historial_estado (id_usuario_cambio);
CREATE INDEX IF NOT EXISTS ix_historial_estado_fecha
    ON historial_estado (fecha);

CREATE OR REPLACE FUNCTION recalcular_total_pedido()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    pedido_actual integer;
    pedido_anterior integer;
BEGIN
    pedido_actual := CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE NEW.id_pedido END;
    pedido_anterior := CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.id_pedido END;

    IF pedido_actual IS NOT NULL THEN
        UPDATE pedido
        SET valor_total = COALESCE(
                (
                    SELECT SUM(cantidad * precio_unitario)
                    FROM detalle_pedido
                    WHERE id_pedido = pedido_actual
                ),
                0
            ),
            fecha_ultima_actualizacion = CURRENT_TIMESTAMP
        WHERE id_pedido = pedido_actual;
    END IF;

    IF pedido_anterior IS NOT NULL
       AND pedido_anterior IS DISTINCT FROM pedido_actual THEN
        UPDATE pedido
        SET valor_total = COALESCE(
                (
                    SELECT SUM(cantidad * precio_unitario)
                    FROM detalle_pedido
                    WHERE id_pedido = pedido_anterior
                ),
                0
            ),
            fecha_ultima_actualizacion = CURRENT_TIMESTAMP
        WHERE id_pedido = pedido_anterior;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'trg_detalle_recalcular_total'
          AND tgrelid = 'detalle_pedido'::regclass
    ) THEN
        CREATE TRIGGER trg_detalle_recalcular_total
        AFTER INSERT OR UPDATE OR DELETE ON detalle_pedido
        FOR EACH ROW
        EXECUTE FUNCTION recalcular_total_pedido();
    END IF;
END
$$;

COMMIT;
